import {chromium} from 'playwright';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const out=path.resolve('outputs/lead-hunt-2026-10-08');
const base=process.env.QA_URL||'http://localhost:3018';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.join(out,'Kapadiya-Lead-Desk.html')).href);
assert.equal(await page.locator('#rows tr').count(),34);
assert.equal(await page.locator('#rows a[href^="mailto:"]').count(),31);
const sample=await page.locator('#rows a[href^="https://wa.me/"]').first().getAttribute('href');
assert.match(decodeURIComponent(sample),/The Beauty Queen/);
await page.selectOption('#area','Vesu');assert.ok(await page.locator('#rows tr').count()>10);
await page.selectOption('#area','');await page.fill('#q','Beauty Queen');assert.equal(await page.locator('#rows tr').count(),1);await page.fill('#q','');
await page.locator('[data-open="K001"]').first().click();
await page.locator('[data-log="call"]').click();assert.match(await page.locator('#metrics').innerText(),/Calls\n1/);
await page.reload();assert.match(await page.locator('#metrics').innerText(),/Calls\n1/);
await page.locator('[data-open="K001"]').first().click();await page.selectOption('#status','Do not contact');await page.click('#saveLead');assert.equal(await page.locator('#openWa').isDisabled(),true);
await page.click('#close');assert.match(await page.locator('#rows tr').first().innerText(),/Outreach stopped/);
await page.evaluate(()=>localStorage.removeItem('kapadiya-lead-desk-v1'));await page.reload();
await page.screenshot({path:path.join(out,'desk-desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'desk-mobile.png'),fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
await page.setViewportSize({width:1440,height:1000});
await page.goto(base);await page.waitForLoadState('networkidle');
assert.ok(await page.locator('h1').innerText());
assert.equal(await page.locator('img').evaluateAll(xs=>xs.filter(i=>!i.complete||!i.naturalWidth).length),0);
for(const p of ['/brochures/AI-Fashion-Modelling-Portfolio.pdf','/brochures/Kapadiya-Service-Guide.pdf']){const r=await page.request.get(base+p);assert.equal(r.status(),200)}
await page.screenshot({path:path.join(out,'site-desktop.png'),fullPage:true});
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'site-mobile.png'),fullPage:true});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
assert.deepEqual(errors,[]);await browser.close();
await fs.writeFile(path.join(out,'qa-results.json'),JSON.stringify({status:'passed',checks:['34 leads','31 email draft links','personalized WhatsApp URL','search and area filters','explicit action logging','persistence on reload','opt-out blocks outreach','mobile overflow','homepage assets','both PDF downloads','zero page errors'],outreachSent:0},null,2));
console.log('PASS: lead desk workflow, opt-out, persistence, responsive site and brochure downloads. No outreach sent.');
